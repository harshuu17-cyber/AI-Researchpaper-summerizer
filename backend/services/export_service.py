def generate_pdf_summary_file(payload: Dict[str, Any], output_path: Path) -> Path:
    """
    Generate an elegant multi-page PDF summary document using PyMuPDF.
    """
    doc = pymupdf.open()
    analysis = payload.get("analysis", {})
    numerical = payload.get("numerical_results", {}).get("results", [])
    title = analysis.get("title", "Research Paper Summary")
    authors = analysis.get("authors", "Not specified")
    area = analysis.get("research_area", "Not specified")
    pages = payload.get("page_count", "N/A")
    words = payload.get("word_count", "N/A")
    words_str = f"{words:,}" if isinstance(words, int) else str(words)

    page_w, page_h = 595, 842  # Standard A4
    margin = 44
    usable_w = page_w - (2 * margin)

    page_num = 1
    page = doc.new_page(width=page_w, height=page_h)
    y = margin

    def check_page_space(needed_height: float):
        nonlocal page, y, page_num
        if y + needed_height > page_h - margin - 25:
            # Draw footer for current page
            footer_rect = pymupdf.Rect(margin, page_h - margin, margin + usable_w, page_h - margin + 14)
            page.insert_textbox(
                footer_rect,
                f"Page {page_num} | ResearchLens Academic Summary",
                fontsize=8,
                fontname="helv",
                color=(0.48, 0.54, 0.64),
                align=pymupdf.TEXT_ALIGN_RIGHT,
            )
            page = doc.new_page(width=page_w, height=page_h)
            page_num += 1
            y = margin

    # Brand top banner accent
    top_bar = pymupdf.Rect(margin, y, margin + usable_w, y + 4)
    page.draw_rect(top_bar, color=(0.33, 0.39, 0.85), fill=(0.33, 0.39, 0.85))
    y += 14

    lbl_rect = pymupdf.Rect(margin, y, margin + usable_w, y + 14)
    page.insert_textbox(
        lbl_rect,
        "RESEARCHLENS • EXECUTIVE RESEARCH SUMMARY",
        fontsize=8.5,
        fontname="helv",
        color=(0.33, 0.39, 0.85),
    )
    y += 18

    # Title
    t_rect = pymupdf.Rect(margin, y, margin + usable_w, y + 45)
    page.insert_textbox(
        t_rect,
        title,
        fontsize=14.5,
        fontname="helv",
        color=(0.09, 0.13, 0.2),
    )
    y += 50

    # Meta
    meta_line = f"Authors: {authors}   |   Area: {area}   |   {pages} Pages   |   {words_str} Words"
    m_rect = pymupdf.Rect(margin, y, margin + usable_w, y + 18)
    page.insert_textbox(
        m_rect,
        meta_line,
        fontsize=8.5,
        fontname="helv",
        color=(0.38, 0.44, 0.54),
    )
    y += 24

    # Divider line
    page.draw_line(
        pymupdf.Point(margin, y),
        pymupdf.Point(margin + usable_w, y),
        color=(0.85, 0.88, 0.93),
        width=1,
    )
    y += 18

    # Sections to render
    sections: List[tuple[str, str]] = []

    tldr = analysis.get("tldr")
    if tldr and tldr != "Not specified in the paper":
        sections.append(("Executive TL;DR", tldr))

    abstract = analysis.get("abstract_summary")
    if abstract:
        sections.append(("1. Abstract Summary", abstract))

    prob = analysis.get("research_problem", "")
    obj = analysis.get("objective", "")
    contributions = analysis.get("key_contributions", [])
    if prob or obj or contributions:
        prob_obj_text = ""
        if prob:
            prob_obj_text += f"Problem:\n{prob}"
        if obj:
            if prob_obj_text:
                prob_obj_text += "\n\n"
            prob_obj_text += f"Objective:\n{obj}"
        if contributions:
            if prob_obj_text:
                prob_obj_text += "\n\n"
            prob_obj_text += "Key Novel Contributions:\n" + "\n".join([f"• {c}" for c in contributions])
        sections.append(("2. Research Problem, Objective & Contributions", prob_obj_text))

    method = analysis.get("methodology", "")
    dataset = analysis.get("dataset", "")
    models = analysis.get("models_or_algorithms", [])
    if method or dataset or models:
        m_text = method
        if models:
            m_text += "\n\nModels / Algorithms: " + ", ".join(models)
        if dataset:
            m_text += f"\nDataset: {dataset}"
        sections.append(("3. Methodology & System Architecture", m_text))

    findings = analysis.get("key_findings", [])
    results = analysis.get("key_results", [])
    if findings or results:
        res_text = ""
        if findings:
            res_text += "Key Findings:\n" + "\n".join([f"• {f}" for f in findings])
        if results:
            if res_text:
                res_text += "\n\n"
            res_text += "Key Results:\n" + "\n".join([f"• {r}" for r in results])
        sections.append(("4. Key Findings & Results", res_text))

    applications = analysis.get("practical_applications", [])
    if applications:
        app_text = "\n".join([f"• {a}" for a in applications])
        sections.append(("5. Practical Applications & Use Cases", app_text))

    if numerical:
        num_text = "\n".join([
            f"• {item.get('metric', 'Metric')}: {item.get('value', '')} {item.get('unit', '')} ({item.get('label', 'Overall')})"
            for item in numerical
        ])
        sections.append(("6. Quantitative Evidence & Numerical Results", num_text))

    conclusion = analysis.get("conclusion")
    if conclusion:
        sections.append(("7. Conclusion", conclusion))

    limitations = analysis.get("limitations", [])
    future = analysis.get("future_work", [])
    if limitations or future:
        lim_text = ""
        if limitations:
            lim_text += "Limitations:\n" + "\n".join([f"• {l}" for l in limitations])
        if future:
            if lim_text:
                lim_text += "\n\n"
            lim_text += "Future Work:\n" + "\n".join([f"• {fw}" for fw in future])
        sections.append(("8. Limitations & Future Work", lim_text))

    for heading, text in sections:
        if not text or not text.strip():
            continue
        check_page_space(55)

        # Heading box
        h_rect = pymupdf.Rect(margin, y, margin + usable_w, y + 18)
        page.insert_textbox(
            h_rect,
            heading,
            fontsize=11,
            fontname="helv",
            color=(0.18, 0.23, 0.42),
        )
        y += 22

        # Render paragraphs safely across pages without slicing errors
        paragraphs = [p.strip() for p in text.split("\n") if p.strip()]
        for para in paragraphs:
            est_lines = max(1, len(para) // 72 + 1)
            para_h = est_lines * 14 + 6
            check_page_space(para_h)

            t_rect = pymupdf.Rect(margin, y, margin + usable_w, y + para_h)
            page.insert_textbox(
                t_rect,
                para,
                fontsize=9.5,
                fontname="helv",
                color=(0.22, 0.26, 0.35),
            )
            y += para_h + 4

        y += 8

    # Final page footer
    footer_rect = pymupdf.Rect(margin, page_h - margin, margin + usable_w, page_h - margin + 14)
    page.insert_textbox(
        footer_rect,
        f"Page {page_num} | ResearchLens Academic Summary",
        fontsize=8,
        fontname="helv",
        color=(0.48, 0.54, 0.64),
        align=pymupdf.TEXT_ALIGN_RIGHT,
    )

    output_path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(output_path))
    doc.close()
    return output_path


def ensure_summary_files(paper_id: str, payload: Dict[str, Any], outputs_dir: Path) -> Dict[str, Path]:
    """
    Ensure all export formats (.md, .txt, .pdf, .json) are generated and available on disk.
    """
    outputs_dir.mkdir(parents=True, exist_ok=True)
    results = {}

    md_path = outputs_dir / f"{paper_id}_summary.md"
    if not md_path.exists():
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(generate_markdown_summary(payload))
    results["md"] = md_path

    txt_path = outputs_dir / f"{paper_id}_summary.txt"
    if not txt_path.exists():
        with open(txt_path, "w", encoding="utf-8") as f:
            f.write(generate_text_summary(payload))
    results["txt"] = txt_path

    json_path = outputs_dir / f"{paper_id}_data.json"
    if not json_path.exists():
        with open(json_path, "w", encoding="utf-8") as f:
            json.dump(payload, f, indent=2)
    results["json"] = json_path

    pdf_path = outputs_dir / f"{paper_id}_summary.pdf"
    if not pdf_path.exists():
        try:
            generate_pdf_summary_file(payload, pdf_path)
            results["pdf"] = pdf_path
        except Exception as e:
            print(f"[ResearchLens] Warning: Failed to generate PDF summary: {e}")
    else:
        results["pdf"] = pdf_path

    return results
