def generate_markdown_summary(payload: Dict[str, Any]) -> str:
    """
    Generate an academic-grade formatted Markdown summary document
    from paper analysis results.
    """
    analysis = payload.get("analysis", {})
    numerical = payload.get("numerical_results", {}).get("results", [])
    title = analysis.get("title", "Research Paper Summary")
    authors = analysis.get("authors", "Not specified")
    area = analysis.get("research_area", "Not specified")
    keywords = ", ".join(analysis.get("keywords", []))
    pages = payload.get("page_count", "N/A")
    words = payload.get("word_count", "N/A")
    words_str = f"{words:,}" if isinstance(words, int) else str(words)

    lines = [
        f"# ResearchLens Summary: {title}",
        "",
        f"**Authors:** {authors}  ",
        f"**Research Area:** {area}  ",
    ]
    if keywords:
        lines.append(f"**Keywords:** {keywords}  ")
    lines.extend([
        f"**Document Info:** {pages} pages | {words_str} words  ",
        "",
        "---",
        "",
    ])

    tldr = analysis.get("tldr")
    if tldr and tldr != "Not specified in the paper":
        lines.extend([
            f"> **Executive TL;DR:** {tldr}",
            "",
            "---",
            "",
        ])

    lines.extend([
        "## 1. Abstract Summary",
        analysis.get("abstract_summary", "Not specified"),
        "",
        "---",
        "",
        "## 2. Research Problem & Objective",
        "### Research Problem",
        analysis.get("research_problem", "Not specified"),
        "",
        "### Objective",
        analysis.get("objective", "Not specified"),
        "",
    ])

    contributions = analysis.get("key_contributions", [])
    if contributions:
        lines.append("### Key Novel Contributions")
        for c in contributions:
            lines.append(f"- {c}")
        lines.append("")

    lines.extend([
        "---",
        "",
        "## 3. Methodology & System Architecture",
        analysis.get("methodology", "Not specified"),
        "",
    ])

    models = analysis.get("models_or_algorithms", [])
    if models:
        lines.append("### Models / Algorithms")
        for m in models:
            lines.append(f"- {m}")
        lines.append("")

    lines.extend([
        "### Dataset",
        analysis.get("dataset", "Not specified"),
        "",
        "---",
        "",
        "## 4. Key Findings & Results",
    ])

    findings = analysis.get("key_findings", [])
    if findings:
        lines.append("### Key Findings")
        for f in findings:
            lines.append(f"- {f}")
        lines.append("")

    results = analysis.get("key_results", [])
    if results:
        lines.append("### Key Results")
        for r in results:
            lines.append(f"- {r}")
        lines.append("")

    applications = analysis.get("practical_applications", [])
    if applications:
        lines.extend([
            "---",
            "",
            "## 5. Practical Applications & Use Cases",
        ])
        for app in applications:
            lines.append(f"- {app}")
        lines.append("")

    if numerical:
        lines.extend([
            "---",
            "",
            "## 6. Quantitative Evidence & Numerical Results",
            "",
            "| Metric | Measurement / Value | Unit | Context / Label |",
            "| :--- | :--- | :--- | :--- |",
        ])
        for row in numerical:
            metric = row.get("metric", "N/A")
            val = row.get("value", "")
            unit = row.get("unit", "")
            lbl = row.get("label", "Overall")
            lines.append(f"| {metric} | {val} | {unit} | {lbl} |")
        lines.append("")

    lines.extend([
        "---",
        "",
        "## 7. Conclusion",
        analysis.get("conclusion", "Not specified"),
        "",
        "---",
        "",
        "## 8. Limitations & Future Work",
    ])

    limitations = analysis.get("limitations", [])
    if limitations:
        lines.append("### Limitations")
        for lim in limitations:
            lines.append(f"- {lim}")
        lines.append("")

    future_work = analysis.get("future_work", [])
    if future_work:
        lines.append("### Future Work")
        for fw in future_work:
            lines.append(f"- {fw}")
        lines.append("")

    lines.extend([
        "---",
        "*Generated by ResearchLens — AI-Powered Research Paper Intelligence*",
        ""
    ])

    return "\n".join(lines)


